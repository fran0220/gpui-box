#[cfg(test)]
mod tests {
    use super::*;

    fn placeholders(text: &str) -> Vec<&str> {
        let mut slots: Vec<_> = text
            .split('{')
            .skip(1)
            .map(|part| {
                let (index, _) = part.split_once('}').expect("closed placeholder");
                assert!(
                    index.parse::<usize>().is_ok(),
                    "positional template: {text}"
                );
                index
            })
            .collect();
        slots.sort_unstable();
        slots
    }

    #[test]
    fn builtin_packs_are_complete_and_preserve_every_placeholder() {
        for &pack in TranslationPack::ALL {
            let strings = pack.strings();
            for &key in StringKey::ALL {
                let translated = pack.text(key);
                assert!(!translated.trim().is_empty(), "{pack:?}: {key:?}");
                assert_eq!(
                    placeholders(translated),
                    placeholders(key.english()),
                    "{pack:?}: {key:?}"
                );
                assert_eq!(strings.text(key).as_ref(), translated);
                if pack == TranslationPack::SimplifiedChinese {
                    assert!(strings.is_overridden(key));
                }
            }
        }
    }

    #[test]
    fn clipboard_verification_refusal_preserves_submission_and_host_reason() {
        let reason = "宿主拒绝读取（policy:{0}）";
        let key = StringKey::CopyVerificationUnavailable;
        let english = TranslationPack::English.strings().format(key, &[reason]);
        let chinese = TranslationPack::SimplifiedChinese
            .strings()
            .format(key, &[reason]);
        assert_eq!(
            english.as_ref(),
            "Clipboard write submitted; verification unavailable: 宿主拒绝读取（policy:{0}）"
        );
        assert_eq!(
            chinese.as_ref(),
            "写入已提交；无法验证：宿主拒绝读取（policy:{0}）"
        );
        for &pack in TranslationPack::ALL {
            let text = pack.strings().format(key, &[reason]);
            assert_ne!(text.as_ref(), pack.text(StringKey::CopyDone));
            assert_ne!(text.as_ref(), pack.text(StringKey::CopyFailedDetail));
        }
    }

    #[test]
    fn builtin_packs_reorder_values_without_changing_facts_or_caller_overrides() {
        let mut strings = TranslationPack::SimplifiedChinese.strings();
        assert_eq!(
            strings
                .format(StringKey::GridSelectionCounts, &["2", "7", "19"])
                .as_ref(),
            "已加载 7 项，选中 2 项，总计 19 项"
        );
        assert_eq!(
            strings
                .format(StringKey::ApprovalAlwaysPath, &["/work"])
                .as_ref(),
            "在 /work 中始终批准"
        );
        assert_eq!(
            strings
                .format(StringKey::ApprovalAlwaysHost, &["example.test"])
                .as_ref(),
            "在主机 example.test 上始终批准"
        );
        assert_ne!(
            strings.text(StringKey::CopyDone),
            strings.text(StringKey::CopyFailed)
        );
        assert_ne!(
            strings.text(StringKey::AttachmentReady),
            strings.text(StringKey::AttachmentProcessing)
        );
        assert_ne!(
            strings.text(StringKey::BrowserUnavailable),
            strings.text(StringKey::BrowserEmpty)
        );
        strings.set(StringKey::Copy, "复制内容");
        assert_eq!(strings.text(StringKey::Copy).as_ref(), "复制内容");
        assert_eq!(
            TranslationPack::SimplifiedChinese
                .strings()
                .text(StringKey::Copy)
                .as_ref(),
            "复制"
        );
        strings.clear(StringKey::Copy);
        assert_eq!(
            strings.text(StringKey::Copy).as_ref(),
            "Copy",
            "clear retains the existing English-reset contract"
        );
    }
}
