//! Complete built-in UI vocabulary, not automatic locale detection or number/date policy.
use super::{StringKey, Strings};

/// Complete, bundled translations of Kit-owned labels. Caller content is never
/// translated. Install `pack.strings()` with `cx.set_global`, then apply any
/// application-specific overrides through the existing [`Strings`] interface.
/// Number/date adapters, search matching and layout direction stay caller-owned.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TranslationPack {
    English,
    SimplifiedChinese,
}

impl TranslationPack {
    pub const ALL: &'static [Self] = &[Self::English, Self::SimplifiedChinese];

    pub const fn language_tag(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::SimplifiedChinese => "zh-Hans",
        }
    }

    pub fn text(self, key: StringKey) -> &'static str {
        match self {
            Self::English => key.english(),
            Self::SimplifiedChinese => chinese(key),
        }
    }

    /// A fresh caller-owned catalogue; later overrides never mutate the pack.
    pub fn strings(self) -> Strings {
        let mut strings = Strings::new();
        if self != Self::English {
            for &key in StringKey::ALL {
                strings.set(key, self.text(key));
            }
        }
        strings
    }
}

